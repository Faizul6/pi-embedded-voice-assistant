def draw_char(char, page, start_col):
    pattern = FONT.get(char, FONT[' '])
    for i, byte_value in enumerate(pattern):
        set_pixel_byte(page, start_col + i, byte_value)
    set_pixel_byte(page, start_col + 5, 0x00)

def draw_string(text, page=0, start_col=0):
    col = start_col
    for char in text:
        draw_char(char, page, col)
        col += 6

def show_text(line1, line2=""):
    clear_display()
    draw_string(line1[:21], page=0, start_col=2)
    if line2:
        draw_string(line2[:21], page=2, start_col=2)
